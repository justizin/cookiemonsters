#!/usr/bin/env python3
"""Regenerate every derived file from its single source.

  shared/scoring.json            -> api/cookiemonsters/_generated.py (SCORING)
                                    extension/src/common/generated_core.js
  shared/public_suffix_list.dat  -> api/cookiemonsters/_generated.py (PSL)
                                    extension/src/common/generated_core.js
  shared/privacy.md              -> api/cookiemonsters/_generated.py (PRIVACY_MD)
                                    docs/PRIVACY.md
                                    extension/src/options/options.html
  extension/rules/*.json         -> extension/src/common/generated_rules.js
  storage/sql.py SCHEMA          -> api/worker/migrations/0001_init.sql

  python tools/sync_generated.py          write
  python tools/sync_generated.py --check  fail if anything is stale (CI)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "api"))

HEADER_JS = "/* GENERATED by tools/sync_generated.py — do not edit. */\n"


def psl_rules() -> list[str]:
    rules = []
    for line in (ROOT / "shared/public_suffix_list.dat").read_text("utf-8").splitlines():
        line = line.strip().split()[0] if line.strip() else ""
        if not line or line.startswith("//"):
            continue
        prefix = ""
        if line.startswith("!"):
            prefix, line = "!", line[1:]
        elif line.startswith("*."):
            prefix, line = "*.", line[2:]
        try:
            ascii_rule = ".".join(lab.encode("idna").decode("ascii") if lab != "*" else lab for lab in line.lower().split("."))
        except UnicodeError:
            continue
        rules.append(prefix + ascii_rule)
    return sorted(set(rules))


GENERATED_PY = ROOT / "api/cookiemonsters/_generated.py"


def generated_py() -> str:
    """Data ships as a Python module (not package data files) so it imports the same way
    under CPython, an installed wheel, and Pyodide in a Cloudflare Python Worker."""
    scoring = json.loads((ROOT / "shared/scoring.json").read_text("utf-8"))
    privacy = (ROOT / "shared/privacy.md").read_text("utf-8")
    return (
        '"""GENERATED by tools/sync_generated.py from shared/ — do not edit.\n\n'
        'PSL is derived from the Public Suffix List (MPL-2.0, https://publicsuffix.org)."""\n\n'
        f"SCORING = {scoring!r}\n\n"
        f"PRIVACY_MD = {privacy!r}\n\n"
        f"PSL = {chr(10).join(psl_rules())!r}\n"
    )


def outputs() -> dict[Path, str]:
    sys.path.insert(0, str(ROOT / "api"))
    from cookiemonsters import mdlite  # noqa: E402  (pure module, no generated data needed)

    scoring = json.loads((ROOT / "shared/scoring.json").read_text("utf-8"))
    rules = json.loads((ROOT / "extension/rules/cmps.json").read_text("utf-8"))
    heur = json.loads((ROOT / "extension/rules/heuristics.json").read_text("utf-8"))
    privacy = (ROOT / "shared/privacy.md").read_text("utf-8")
    psl = psl_rules()

    out: dict[Path, str] = {}
    out[GENERATED_PY] = generated_py()
    out[ROOT / "docs/PRIVACY.md"] = "<!-- GENERATED from shared/privacy.md by tools/sync_generated.py — edit that file instead. -->\n\n" + privacy

    core = {"scoring": scoring, "psl": "\n".join(psl)}
    out[ROOT / "extension/src/common/generated_core.js"] = HEADER_JS + "globalThis.CM_CORE_DATA = " + json.dumps(core, ensure_ascii=False, separators=(",", ":")) + ";\n"
    rules_data = {"rules": {"version": rules["version"], "cmps": rules["cmps"]}, "heuristics": {k: v for k, v in heur.items() if k != "comment"}}
    out[ROOT / "extension/src/common/generated_rules.js"] = HEADER_JS + "globalThis.CM_RULES_DATA = " + json.dumps(rules_data, ensure_ascii=False, indent=1) + ";\n"

    template = (ROOT / "extension/src/options/options.template.html").read_text("utf-8")
    out[ROOT / "extension/src/options/options.html"] = template.replace("{{PRIVACY}}", mdlite.to_html(privacy))

    from cookiemonsters.storage.sql import SCHEMA

    out[ROOT / "api/worker/migrations/0001_init.sql"] = (
        "-- GENERATED from api/cookiemonsters/storage/sql.py by tools/sync_generated.py.\n"
        "-- Apply with: npx wrangler d1 migrations apply cookiemonsters --remote\n\n" + ";\n\n".join(SCHEMA) + ";\n"
    )
    return out


def main() -> int:
    check = "--check" in sys.argv
    if not GENERATED_PY.exists():  # bootstrap: the package needs it to import storage.sql
        GENERATED_PY.write_text(generated_py(), "utf-8")
    stale = []
    for path, content in outputs().items():
        current = path.read_text("utf-8") if path.exists() else None
        if current != content:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, "utf-8")
    if check and stale:
        print("stale generated files (run tools/sync_generated.py):", *stale, sep="\n  ")
        return 1
    print(("checked" if check else "wrote") + f" generated files; {len(stale)} {'stale' if check else 'updated'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
